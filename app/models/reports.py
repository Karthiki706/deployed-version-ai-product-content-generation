from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional


# ─────────────────────────────────────────────────────────────────────────────
# Hallucination
# ─────────────────────────────────────────────────────────────────────────────

class HallucinationViolation(BaseModel):
    field: str
    issue: str


class UnsupportedClaim(BaseModel):
    """An AI-generated claim not supported by the validated input attributes."""
    claim: str
    reason: str
    severity: str = "Medium"   # Low | Medium | High
    impact: List[str] = Field(default_factory=list)  # e.g. ["Customer Trust", "Compliance"]


class HallucinationSectionA(BaseModel):
    """Category validation context."""
    detected_category: str = ""
    validation_confidence: float = 1.0
    validation_status: str = "PASS"   # PASS | DEGRADED | SKIPPED


class HallucinationSectionB(BaseModel):
    """Attributes rejected by the semantic validator (invalid user input)."""
    rejected_attributes: List[Dict[str, str]] = Field(default_factory=list)
    # Each entry: {"attribute": str, "reason": str}


class HallucinationSectionC(BaseModel):
    """Unsupported claims generated by the LLM (actual AI hallucinations)."""
    unsupported_claims: List[UnsupportedClaim] = Field(default_factory=list)


class HallucinationSectionD(BaseModel):
    """Summary distinguishing invalid-user-input from LLM hallucinations."""
    hallucination_status: str = "PASS"
    summary: str = ""
    rejected_input_count: int = 0
    ai_hallucination_count: int = 0
    ai_hallucination_high_severity_count: int = 0


class HallucinationReport(BaseModel):
    # Legacy fields — kept for backward compatibility with existing orchestrator/frontend
    hallucinated_fields: List[HallucinationViolation] = Field(default_factory=list)
    missing_fields: List[str] = Field(default_factory=list)
    unsupported_claims: List[str] = Field(default_factory=list)
    confidence: float = 1.0
    score: float = 100.0
    comparison_report: List[Dict[str, Any]] = Field(default_factory=list)

    # New structured sections
    section_a: Optional[HallucinationSectionA] = None
    section_b: Optional[HallucinationSectionB] = None
    section_c: Optional[HallucinationSectionC] = None
    section_d: Optional[HallucinationSectionD] = None


# ─────────────────────────────────────────────────────────────────────────────
# SEO
# ─────────────────────────────────────────────────────────────────────────────

class KeywordAuditEntry(BaseModel):
    keyword: str
    density: float
    status: str             # OPTIMIZED | NEEDS_IMPROVEMENT | MISSING
    recommendation: Optional[str] = None


class SEOAuditSummary(BaseModel):
    total: int = 0
    optimized: int = 0
    needs_improvement: int = 0
    missing: int = 0


class SEOReport(BaseModel):
    # Legacy fields
    missing_keywords: List[str] = Field(default_factory=list)
    keyword_density: Dict[str, float] = Field(default_factory=dict)
    meta_description_length: int = 0
    long_description_length: int = 0
    title_length: int = 0
    duplicate_keywords: List[str] = Field(default_factory=list)
    readability_score: float = 100.0
    score: float = 100.0

    # New structured audit
    keyword_audit: List[KeywordAuditEntry] = Field(default_factory=list)
    audit_summary: Optional[SEOAuditSummary] = None


# ─────────────────────────────────────────────────────────────────────────────
# Brand
# ─────────────────────────────────────────────────────────────────────────────

class BrandReport(BaseModel):
    violations: List[str] = Field(default_factory=list)
    tone_check: str = "PASS"
    voice_compliance: bool = True
    writing_style_check: str = "PASS"
    score: float = 100.0


# ─────────────────────────────────────────────────────────────────────────────
# Quality
# ─────────────────────────────────────────────────────────────────────────────

class ScoreComponent(BaseModel):
    score: float
    reason: str
    penalty: float = 0.0


class SafetySubScores(BaseModel):
    content_safety: float = 100.0
    brand_safety: float = 100.0
    category_safety: float = 100.0
    validation_safety: float = 100.0
    policy_safety: float = 100.0


class SafetyBreakdown(ScoreComponent):
    risk_level: str = "Low"   # Low | Medium | High | Critical
    sub_scores: Optional[SafetySubScores] = None


class QualityBreakdown(BaseModel):
    generation_quality: Optional[ScoreComponent] = None
    seo: Optional[ScoreComponent] = None
    safety: Optional[SafetyBreakdown] = None
    brand_compliance: Optional[ScoreComponent] = None
    validation: Optional[ScoreComponent] = None
    hallucination: Optional[ScoreComponent] = None


class QualityReport(BaseModel):
    # Legacy fields
    seo_score: float = 100.0
    brand_score: float = 100.0
    hallucination_score: float = 100.0
    overall_quality: float = 100.0
    confidence: float = 1.0

    # New structured fields
    safety_score: float = 100.0
    validation_confidence: float = 1.0
    generation_confidence: float = 1.0
    breakdown: Optional[QualityBreakdown] = None
    risk_level: str = "Low"
